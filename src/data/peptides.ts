/** Reconstitution maths shared by the calculator UI and server-rendered examples. */
export function reconstitute(vialMg: number, waterMl: number, doseMcg: number) {
  const concentrationMgPerMl = vialMg / waterMl;
  const doseMl = doseMcg / 1000 / concentrationMgPerMl;
  const units = doseMl * 100;
  const dosesPerVial = Math.floor((vialMg * 1000) / doseMcg);
  return { concentrationMgPerMl, doseMl, units, dosesPerVial };
}
